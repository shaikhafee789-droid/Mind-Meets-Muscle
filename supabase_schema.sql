-- Problem Crackers MVP schema for Supabase/PostgreSQL
-- Run in Supabase SQL Editor after creating a project.

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  full_name text not null,
  email text,
  mobile text,
  avatar_url text,
  headline text,
  location text,
  created_at timestamptz default now()
);

create table if not exists public.user_roles (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(id) on delete cascade,
  role text not null check (role in ('idea_owner','developer','business_owner','admin')),
  unique (user_id, role)
);

create table if not exists public.ideas (
  id bigint generated by default as identity primary key,
  owner_id uuid not null references public.profiles(id) on delete cascade,
  title text not null,
  description text not null,
  problem text,
  proposed_solution text,
  required_skills text[] default '{}',
  category text,
  expected_outcome text,
  budget text,
  timeline text,
  collaboration_preference text,
  status text default 'looking_for_team',
  created_at timestamptz default now()
);

create table if not exists public.skills (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(id) on delete cascade,
  professional_headline text,
  technical_skills text[] default '{}',
  languages text[] default '{}',
  frameworks text[] default '{}',
  tools text[] default '{}',
  experience_level text,
  portfolio_url text,
  github_url text,
  linkedin_url text,
  introduction text,
  created_at timestamptz default now()
);

create table if not exists public.businesses (
  id bigint generated by default as identity primary key,
  owner_id uuid not null references public.profiles(id) on delete cascade,
  name text not null,
  category text,
  description text,
  owner_name text,
  contact_email text,
  mobile text,
  location text,
  city text,
  state text,
  country text,
  website_url text,
  required_solutions text[] default '{}',
  logo_url text,
  created_at timestamptz default now()
);

create table if not exists public.collaboration_requests (
  id bigint generated by default as identity primary key,
  requester_id uuid not null references public.profiles(id) on delete cascade,
  target_user_id uuid references public.profiles(id) on delete cascade,
  idea_id bigint references public.ideas(id) on delete cascade,
  business_id bigint references public.businesses(id) on delete cascade,
  status text not null default 'pending' check (status in ('pending','accepted','rejected','cancelled')),
  message text,
  created_at timestamptz default now()
);

create table if not exists public.projects (
  id bigint generated by default as identity primary key,
  owner_id uuid not null references public.profiles(id) on delete cascade,
  title text not null,
  description text,
  status text default 'looking_for_team',
  progress integer default 0 check (progress between 0 and 100),
  idea_id bigint references public.ideas(id),
  created_at timestamptz default now()
);

create table if not exists public.project_members (
  project_id bigint not null references public.projects(id) on delete cascade,
  user_id uuid not null references public.profiles(id) on delete cascade,
  role text,
  primary key (project_id, user_id)
);

create table if not exists public.messages (
  id bigint generated by default as identity primary key,
  sender_id uuid not null references public.profiles(id) on delete cascade,
  recipient_id uuid references public.profiles(id) on delete cascade,
  project_id bigint references public.projects(id) on delete cascade,
  content text not null,
  created_at timestamptz default now()
);

create table if not exists public.notifications (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(id) on delete cascade,
  title text not null,
  body text,
  link text,
  unread boolean default true,
  created_at timestamptz default now()
);

create table if not exists public.saved_items (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(id) on delete cascade,
  item_type text not null,
  item_id bigint not null,
  created_at timestamptz default now(),
  unique (user_id, item_type, item_id)
);

create table if not exists public.reports (
  id bigint generated by default as identity primary key,
  reporter_id uuid not null references public.profiles(id) on delete cascade,
  target_type text not null,
  target_id bigint not null,
  reason text not null,
  status text default 'open',
  created_at timestamptz default now()
);

