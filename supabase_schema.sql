create policy "Public profiles are readable" on public.profiles for select using (true);
create policy "Users update own profile" on public.profiles for update using (auth.uid() = id);
create policy "Users insert own profile" on public.profiles for insert with check (auth.uid() = id);

create policy "Users read own roles" on public.user_roles for select using (auth.uid() = user_id);
create policy "Users insert own roles" on public.user_roles for insert with check (auth.uid() = user_id);

create policy "Published ideas are readable" on public.ideas for select using (true);
create policy "Users manage own ideas" on public.ideas for all using (auth.uid() = owner_id) with check (auth.uid() = owner_id);

create policy "Skills are readable" on public.skills for select using (true);
create policy "Users manage own skills" on public.skills for all using (auth.uid() = user_id) with check (auth.uid() = user_id);

create policy "Businesses are readable" on public.businesses for select using (true);
create policy "Users manage own businesses" on public.businesses for all using (auth.uid() = owner_id) with check (auth.uid() = owner_id);

create policy "Users see collaboration requests involving them" on public.collaboration_requests for select using (auth.uid() = requester_id or auth.uid() = target_user_id);
create policy "Users create collaboration requests" on public.collaboration_requests for insert with check (auth.uid() = requester_id);
create policy "Targets update collaboration requests" on public.collaboration_requests for update using (auth.uid() = target_user_id);

create policy "Project members read projects" on public.projects for select using (exists (select 1 from public.project_members pm where pm.project_id = projects.id and pm.user_id = auth.uid()) or auth.uid() = owner_id);
create policy "Owners manage projects" on public.projects for all using (auth.uid() = owner_id) with check (auth.uid() = owner_id);

create policy "Project members read membership" on public.project_members for select using (auth.uid() = user_id or exists (select 1 from public.projects p where p.id = project_id and p.owner_id = auth.uid()));
create policy "Project owners manage membership" on public.project_members for all using (exists (select 1 from public.projects p where p.id = project_id and p.owner_id = auth.uid()));

create policy "Users read own messages" on public.messages for select using (auth.uid() = sender_id or auth.uid() = recipient_id);
create policy "Users send messages" on public.messages for insert with check (auth.uid() = sender_id);

create policy "Users read own notifications" on public.notifications for select using (auth.uid() = user_id);
create policy "Users update own notifications" on public.notifications for update using (auth.uid() = user_id);

create policy "Users manage own saved items" on public.saved_items for all using (auth.uid() = user_id) with check (auth.uid() = user_id);
create policy "Users create reports" on public.reports for insert with check (auth.uid() = reporter_id);

create or replace function public.handle_new_user()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  insert into public.profiles (id, full_name, email)
  values (new.id, coalesce(new.raw_user_meta_data->>'full_name', split_part(new.email,'@',1)), new.email)
  on conflict (id) do update set email = excluded.email;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
after insert on auth.users
for each row execute function public.handle_new_user();
